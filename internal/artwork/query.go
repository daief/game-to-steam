package artwork

import (
	"game-to-steam/internal/model"
	"path/filepath"
	"strings"
	"unicode"
)

// SearchQuery prefers an existing English display name. Localized manifests
// have no separate English title; use readable installation/program names,
// never Epic's opaque AppName. This is a search hint, not a renamed game.
func SearchQuery(game model.Game) string {
	name := strings.TrimSpace(game.Name)
	if readableEnglish(name) {
		return name
	}
	folder := pathName(game.InstallDir)
	exe := pathName(game.Executable)
	exe = strings.TrimSuffix(exe, filepath.Ext(exe))
	for _, suffix := range []string{"-Win64-Shipping", "-Win32-Shipping", "_Win64_Shipping", "_Win32_Shipping", "-Shipping", "_Shipping"} {
		if strings.HasSuffix(strings.ToLower(exe), strings.ToLower(suffix)) {
			exe = exe[:len(exe)-len(suffix)]
			break
		}
	}
	folderOK, exeOK := readableEnglish(folder), readableEnglish(exe)
	if folderOK && exeOK {
		prefix := 0
		for prefix < min(len(folder), len(exe)) && strings.EqualFold(folder[prefix:prefix+1], exe[prefix:prefix+1]) {
			prefix++
		}
		// Shared title stem avoids autogenerated folder suffixes and executable
		// abbreviations (e.g. BloodstainedftBhx / BloodstainedRotN).
		if prefix >= 4 && (prefix == len(folder) || prefix == len(exe) || camelBoundary(exe, prefix) || camelBoundary(folder, prefix)) {
			return splitTitle(folder[:prefix])
		}
	}
	if folderOK {
		return splitTitle(folder)
	}
	if exeOK {
		return splitTitle(exe)
	}
	return name
}
func pathName(path string) string {
	// Accept saved Windows paths as well as platform-native fixture paths.
	path = strings.TrimRight(strings.ReplaceAll(strings.TrimSpace(path), "\\", "/"), "/")
	if i := strings.LastIndexByte(path, '/'); i >= 0 {
		return path[i+1:]
	}
	return path
}
func readableEnglish(name string) bool {
	letters := 0
	hex := len(name) >= 16
	for _, r := range name {
		if r > 127 {
			return false
		}
		if unicode.IsLetter(r) {
			letters++
		}
		if !strings.ContainsRune("0123456789abcdefABCDEF", r) {
			hex = false
		}
	}
	if letters < 2 || hex {
		return false
	}
	switch strings.ToLower(strings.TrimSpace(name)) {
	case "game", "games", "epic", "epic games", "epicgames", "launcher", "start", "bin", "binaries", "win64", "win32", "shipping":
		return false
	}
	return true
}
func camelBoundary(s string, i int) bool {
	if i <= 0 || i >= len(s) {
		return false
	}
	before, current := rune(s[i-1]), rune(s[i])
	return unicode.IsLower(before) && unicode.IsUpper(current) || unicode.IsLetter(before) && unicode.IsDigit(current) || unicode.IsDigit(before) && unicode.IsLetter(current) || unicode.IsUpper(before) && unicode.IsUpper(current) && i+1 < len(s) && unicode.IsLower(rune(s[i+1]))
}
func splitTitle(s string) string {
	var out strings.Builder
	for i, r := range s {
		if r == '_' || r == '-' {
			out.WriteByte(' ')
			continue
		}
		if camelBoundary(s, i) {
			out.WriteByte(' ')
		}
		out.WriteRune(r)
	}
	return strings.Join(strings.Fields(out.String()), " ")
}
